coefficient_of_variation = function(nonlog_array) {
  sqrt(expm1(sd(log(nonlog_array), na.rm = T)^2))
}

compute_cov = function(data, data_groups) {
  cov = NULL
  ugrp = unique(data_groups)
  for(g in ugrp) {
    g_data = data[ , data_groups == g, drop = FALSE]
    stopifnot("assume at least 3 replicates per group" = ncol(g_data) >= 3)
    # CoV on subset of proteins with 3+ values across replicates
    g_data = g_data[rowSums(!is.na(g_data)) >= 3, , drop = FALSE]
    stopifnot("assume at least 100 rows after filtering for 3+ non-NA values across columns" = nrow(g_data) >= 100)
    g_cov = apply(2^g_data, 1, coefficient_of_variation) # note that CoV function requires non-log input while `mat` is on log2 scale
    cov = c(cov, g_cov)
  }
  return(cov)
}



compute_error_normdata = function(name_data, list_data, col_condition, row_classifications, minval = 2) {
  stopifnot(name_data %in% names(list_data))
  mat_norm = list_data[[name_data]]
  cond_a = mat_norm[,col_condition == "A"]
  cond_b = mat_norm[,col_condition == "B"]
  log2fc = apply(cond_b, 1, mean, na.rm = TRUE) - apply(cond_a, 1, mean, na.rm = TRUE)
  rows = is.finite(log2fc) & rowSums(is.finite(cond_a)) >= minval & rowSums(is.finite(cond_b)) >= minval
  return(tibble(rowid = rownames(mat_norm)[rows], classification = row_classifications[rows], log2fc = log2fc[rows], algo = name_data))
}




apply_normalizations = function(mat_input) {
  list_normdata = list()

  mat_norm = mat_input + 10^-16 # deep copy
  tmp = apply(mat_norm, 2, median, na.rm = TRUE)
  tmp = tmp - mean(tmp)
  for(j in seq_along(tmp)) mat_norm[,j] = mat_norm[,j] - tmp[j]
  list_normdata[["median shift"]] = mat_norm
  # QC; boxplot(mat_norm, outline = F, horizontal = T, las = 1)

  mat_norm = mat_input + 10^-16 # deep copy
  s = pairscale::pairscale_mode(mat_norm, bandwidth_method = "nrd_fast") # updates `mat_norm` by reference
  list_normdata[["pairscale mode"]] = mat_norm

  mat_norm = mat_input + 10^-16 # deep copy
  s = pairscale::pairscale_trimmedmean(mat_norm, trim = 0.2) # updates `mat_norm` by reference
  list_normdata[["pairscale tmean"]] = mat_norm

  mat_norm = mat_input + 10^-16 # deep copy
  list_normdata[["VSN"]] = vsn::justvsn(2^mat_norm) # note; justvsn takes non-log input, returns log2 scaled data

  mat_norm = mat_input + 10^-16 # deep copy
  list_normdata[["Limma Loess"]] = limma::normalizeCyclicLoess(mat_norm, iterations = 10, method = "fast")

  return(list_normdata)
}




